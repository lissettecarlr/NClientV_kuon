package com.maxwai.nclientv3.utility;

import android.content.Context;
import android.util.JsonReader;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;

import com.maxwai.nclientv3.R;
import com.maxwai.nclientv3.api.components.Tag;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Custom (fork only) feature: show a Chinese translation next to the tags.
 * <p>
 * Display only: the tag names used everywhere else (queries, database, clipboard, ...) stay
 * in English. The dictionary is {@code assets/tag_zh.json} ("type:name" -> translation),
 * generated by {@code scripts/build_tag_translations.py} from EhTagTranslation.
 */
public final class TagTranslator {
    private static final String ASSET = "tag_zh.json";
    private static final Object LOCK = new Object();
    private static volatile Map<String, String> dictionary;

    private TagTranslator() {
    }

    public static boolean isEnabled(@NonNull Context context) {
        return context.getSharedPreferences("Settings", 0)
            .getBoolean(context.getString(R.string.preference_key_show_tag_translation), true);
    }

    @Nullable
    public static String translate(@NonNull Context context, @NonNull Tag tag) {
        if (!isEnabled(context) || tag.getType() == null || tag.getName() == null) return null;
        Map<String, String> map = getDictionary(context);
        return map.get(tag.getType().getSingle() + ":" + tag.getName().toLowerCase(Locale.ROOT));
    }

    /**
     * @return "name · 翻译" or just "name" if there is no translation
     */
    @NonNull
    public static String display(@NonNull Context context, @NonNull Tag tag) {
        String translation = translate(context, tag);
        return translation == null ? tag.getName() : tag.getName() + " · " + translation;
    }

    /**
     * Reverse lookup: find the tags whose translation matches {@code text}
     *
     * @return "type:name" keys, exact matches first, then prefix matches, then the others
     */
    @NonNull
    public static List<String> searchKeys(@NonNull Context context, @NonNull String text, int limit) {
        List<String> exact = new ArrayList<>(), prefix = new ArrayList<>(), contains = new ArrayList<>();
        if (text.isEmpty() || !isEnabled(context)) return exact;
        for (Map.Entry<String, String> entry : getDictionary(context).entrySet()) {
            String translation = entry.getValue();
            if (translation.equals(text)) exact.add(entry.getKey());
            else if (translation.startsWith(text)) {
                if (prefix.size() < limit) prefix.add(entry.getKey());
            } else if (contains.size() < limit && translation.contains(text)) contains.add(entry.getKey());
        }
        List<String> result = new ArrayList<>(exact);
        result.addAll(prefix);
        result.addAll(contains);
        return result.size() > limit ? new ArrayList<>(result.subList(0, limit)) : result;
    }

    /**
     * Load the dictionary in background so the first tag list doesn't stall
     */
    public static void preload(@NonNull Context context) {
        if (dictionary != null) return;
        Context app = context.getApplicationContext();
        new Thread(() -> getDictionary(app), "TagTranslatorLoader").start();
    }

    @NonNull
    private static Map<String, String> getDictionary(@NonNull Context context) {
        Map<String, String> map = dictionary;
        if (map != null) return map;
        synchronized (LOCK) {
            if (dictionary != null) return dictionary;
            Map<String, String> loaded = new HashMap<>(1 << 16);
            try (InputStream in = context.getApplicationContext().getAssets().open(ASSET);
                 JsonReader reader = new JsonReader(new InputStreamReader(in, StandardCharsets.UTF_8))) {
                reader.beginObject();
                while (reader.hasNext()) loaded.put(reader.nextName(), reader.nextString());
                reader.endObject();
            } catch (IOException e) {
                LogUtility.e("Unable to load tag translations", e);
            }
            dictionary = loaded;
            return loaded;
        }
    }
}
